import Foundation
import PasswordEntryCore

let path = FileManager.default.temporaryDirectory.appendingPathComponent("password-entry-smoke-\(UUID().uuidString).json")
let password = "TestVaultPassword-2026!"
let testDeviceSecret = Data("smoke-device-secret".utf8)
let store = VaultStore(fileURL: path, deviceSecretOverride: testDeviceSecret)
do {
    try store.unlock(password: "too-short")
    fatalError("weak password was accepted")
} catch VaultError.weakPassword {
} catch {
    fatalError("unexpected weak password error: \(error)")
}
try store.unlock(password: password)
try store.saveEntry(LoginEntry(name: "Example", domains: ["example.com"], username: "demo", password: "secret", totp: TotpConfig(secret: "GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ")))
let favicon = Data([0, 1, 2, 3])
try store.upsertLogin(name: "Example", domain: "https://example.com/login", username: "demo", password: "updated", faviconData: favicon, faviconMimeType: "image/png")
try store.upsertLogin(name: "Example local", domain: "http://example.com:3000/login", username: "demo", password: "local")
let savedEntries = try store.entries()
precondition(savedEntries.first?.origins.contains("http://example.com:3000") == true)
let matched = try store.match(urlString: "https://example.com/sign-in")
precondition(matched.username == "demo" && matched.password == "local")
precondition(matched.domains == ["example.com"])
precondition(matched.faviconData == favicon && matched.faviconMimeType == "image/png")
precondition((try? store.match(urlString: "https://login.example.com/sign-in")) == nil)
precondition((try? store.match(urlString: "http://example.com/sign-in"))?.username == "demo")
precondition((try? store.match(urlString: "https://example.com:8443/sign-in"))?.username == "demo")
let record = try JSONSerialization.jsonObject(with: Data(contentsOf: path)) as? [String: Any]
precondition(record?["version"] as? Int == 2)
let shareMaterial = try ShareCrypto.prepare(entry: matched, includeTotp: false)
precondition(shareMaterial.shareID.count >= 20)
precondition(shareMaterial.envelope.algorithm == "A256GCM")
precondition(!shareMaterial.envelope.iv.isEmpty && !shareMaterial.envelope.ciphertext.isEmpty)
let localShare = ShareRecord(serverShareID: shareMaterial.shareID, entryID: matched.id, viewSecret: shareMaterial.viewSecret, revokeSecret: shareMaterial.revokeSecret, expiresAt: Date().addingTimeInterval(3600))
try store.saveShare(localShare)
let savedShares = try store.shares()
precondition(savedShares.count == 1)
let normalized = LoginEntry(name: "Aliyun", domains: ["https://SIGNIN.ALIYUN.COM/login.htm?callback=x"], username: "u", password: "p")
precondition(normalized.domains == ["signin.aliyun.com"])
let uri = try TotpConfig(otpauthURI: "otpauth://totp/Aliyun%3Au?secret=GEZDGNBVGY3TQOJQ&issuer=Aliyun&digits=6&period=30").validated()
precondition(uri.issuer == "Aliyun" && uri.digits == 6)
store.lockVault()
let reopened = VaultStore(fileURL: path, deviceSecretOverride: testDeviceSecret)
try reopened.unlock(password: password)
let reopenedEntries = try reopened.entries()
precondition(reopenedEntries.count == 1)
precondition(reopenedEntries[0].faviconData == favicon)
let reopenedShares = try reopened.shares()
precondition(reopenedShares.count == 1)
let vector = try TOTP.generate(TotpConfig(secret: "GEZDGNBVGY3TQOJQGEZDGNBVGY3TQOJQ", algorithm: "SHA1", digits: 8), date: Date(timeIntervalSince1970: 59))
precondition(vector == "94287082")
do { try reopened.unlock(password: "wrong-password"); fatalError("wrong password was accepted") } catch { }
try? FileManager.default.removeItem(at: path)
print("PasswordEntryCore smoke checks passed")
